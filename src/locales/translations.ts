export function translateCategoryName(categoryOrName: string | { name?: string } | null | undefined, lang: Language): string {
  if (!categoryOrName) return '';
  const rawName = typeof categoryOrName === 'string'
    ? categoryOrName
    : (typeof categoryOrName === 'object' && categoryOrName !== null && 'name' in categoryOrName && typeof (categoryOrName as { name?: string }).name === 'string')
      ? (categoryOrName as { name?: string }).name!
      : String(categoryOrName || '');

  if (!rawName || typeof rawName !== 'string') return '';
  const item = CATEGORY_NAME_MAP[rawName];
  if (item) return item[lang];
  // check if passed English name
  const lower = rawName.toLowerCase();
  for (const key of Object.keys(CATEGORY_NAME_MAP)) {
    if (CATEGORY_NAME_MAP[key].en.toLowerCase() === lower || CATEGORY_NAME_MAP[key].bn === rawName) {
      return CATEGORY_NAME_MAP[key][lang];
    }
  }
  return rawName;
}

